# ========= Update Cargo.toml and build.rs of both crates


def update_cargo_toml(path, feature_lists):
    """feature_lists is a list of (features, forward_to) pairs. With forward_to
    set, each feature enables the same-named feature of that crate."""
    things = ""
    for feats, forward_to in feature_lists:
        for f in feats:
            name = f["name"].replace("_", "-")
            for val in f["vals"]:
                if forward_to:
                    things += f'{name}-{val} = ["{forward_to}/{name}-{val}"]'
                else:
                    things += f"{name}-{val} = []"
                if val == f["default"]:
                    things += " # Default"
                things += "\n"
            things += "\n"

    SEPARATOR_START = "# BEGIN AUTOGENERATED CONFIG FEATURES\n"
    SEPARATOR_END = "# END AUTOGENERATED CONFIG FEATURES\n"
    HELP = "# Generated by gen_config.py. DO NOT EDIT.\n"
    with open(path, "r") as f:
        data = f.read()
    before, data = data.split(SEPARATOR_START, maxsplit=1)
    _, after = data.split(SEPARATOR_END, maxsplit=1)
    data = before + SEPARATOR_START + HELP + things + SEPARATOR_END + after
    with open(path, "w") as f:
        f.write(data)


def update_build_rs(path, feats):
    things = ""
    for f in feats:
        name = f["name"].upper()
        things += f'    ("{name}", {f["default"]}),\n'

    SEPARATOR_START = "// BEGIN AUTOGENERATED CONFIG FEATURES\n"
    SEPARATOR_END = "// END AUTOGENERATED CONFIG FEATURES\n"
    HELP = "    // Generated by gen_config.py. DO NOT EDIT.\n"
    with open(path, "r") as f:
        data = f.read()
    before, data = data.split(SEPARATOR_START, maxsplit=1)
    _, after = data.split(SEPARATOR_END, maxsplit=1)
    data = before + SEPARATOR_START + HELP + things + "    " + SEPARATOR_END + after
    with open(path, "w") as f:
        f.write(data)


update_cargo_toml("Cargo.toml", [(driver_features, "xarxa-driver"), (features, None)])
update_build_rs("build.rs", features)
update_cargo_toml("xarxa-driver/Cargo.toml", [(driver_features, None)])
update_build_rs("xarxa-driver/build.rs", driver_features)
